"""docs/sources.md and docs/configs.md are generated: the committed copies must be fresh."""

from __future__ import annotations

import importlib.util
from pathlib import Path

from marinedata.registry import Registry

ROOT = Path(__file__).resolve().parents[1]
HEADER = "Generated by scripts/gen_sources_docs.py from registry/ — do not edit"


def _generator():
    path = ROOT / "scripts" / "gen_sources_docs.py"
    spec = importlib.util.spec_from_file_location("gen_sources_docs", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_committed_docs_match_a_fresh_render(tmp_path):
    assert _generator().main(["--out", str(tmp_path)]) == 0
    for name in ("sources.md", "configs.md"):
        fresh = (tmp_path / name).read_text(encoding="utf-8")
        assert (ROOT / "docs" / name).read_text(encoding="utf-8") == fresh, (
            f"docs/{name} is stale: run `make docs` and commit the result"
        )


def test_every_registry_source_has_one_row_and_both_files_carry_the_header():
    sources = (ROOT / "docs" / "sources.md").read_text(encoding="utf-8")
    rows = [line for line in sources.splitlines() if line.startswith("| `")]
    assert len(rows) == len(Registry.load(ROOT / "registry"))
    ids = [line.split("`")[1] for line in rows]
    assert ids == sorted(ids), "rows must stay ordered by id"
    for name in ("sources.md", "configs.md"):
        assert HEADER in (ROOT / "docs" / name).read_text(encoding="utf-8")
