#!/usr/bin/env python
# ruff: noqa: E501
"""Render ``docs/sources.md`` and ``docs/configs.md`` from ``registry/`` and ``hf_export``.

Both files are generated end to end and never hand-edited: ``make docs`` regenerates them and
``make docs-check`` fails when the committed files differ from a fresh render. Rows are ordered
by id, so the output is deterministic. Run from the repo root:

    python scripts/gen_sources_docs.py            # write docs/sources.md and docs/configs.md
    python scripts/gen_sources_docs.py --out DIR  # write them into DIR (used by `make docs-check`)
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from pathlib import Path

import yaml

from marinedata import hf_export as hx
from marinedata.registry import Registry
from marinedata.task_layers import configs as tl
from marinedata.task_layers import mask_configs as mc

ROOT = Path(__file__).resolve().parents[1]
HEADER = "> Generated by scripts/gen_sources_docs.py from registry/ — do not edit."


def _cell(text: object) -> str:
    return " ".join(str(text).split()).replace("|", "\\|") or "—"


def _enum(value: object) -> str:
    return str(getattr(value, "value", value))


def _names(columns) -> str:
    return ", ".join(f"`{name}`" for name, _ in columns)


def _ids(source_ids) -> str:
    return ", ".join(f"`{s}`" for s in sorted(source_ids)) or "—"


def _table(head: list[str], rows: list[list[str]], align: list[str] | None = None) -> list[str]:
    rule = align or ["---"] * len(head)
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join(rule) + " |"]
    return lines + ["| " + " | ".join(r) + " |" for r in rows]


def published_sources(root: Path) -> dict[str, dict]:
    path = root / "registry" / "label-schemes" / "sources.yaml"
    return yaml.safe_load(path.read_text(encoding="utf-8"))["sources"]


def render_sources(registry: Registry, published: dict[str, dict]) -> str:
    sources = sorted(registry, key=lambda s: s.id)
    rows = []
    for s in sources:
        licence = s.licence.id + (" (per row)" if s.licence_per_row else "")
        kinds = ", ".join(sorted({_enum(a.kind) for a in s.annotations}))
        config = published.get(s.id, {}).get("config")
        rows.append(
            [
                f"`{s.id}`", _cell(s.name), _enum(s.access_class), _cell(licence),
                "—" if s.n_images is None else f"{s.n_images:,}", _cell(kinds), _cell(s.version),
                "✓" if s.checksums is not None else "–", f"`{config}`" if config else "–",
            ]
        )  # fmt: skip
    pinned = sum(1 for s in sources if s.checksums is not None)
    shipped = sum(1 for s in sources if s.id in published)
    head = ["id", "title", "access_class", "licence", "n_images", "label types", "version",
            "root_digest", "HF config"]  # fmt: skip
    align = ["---", "---", "---", "---", "---:", "---", "---", ":---:", "---"]
    lines = [
        "# Sources", "", HEADER, "",
        f"{len(sources)} sources · {pinned} with a pinned `root_digest` · {shipped} published on "
        "the Hub. Rows are ordered by id.", "",
        *_table(head, rows, align), "",
        "- `root_digest`: ✓ = `checksums.root_digest` is pinned in the registry, – = not pinned.",
        "- `HF config`: the Hub config the source is published in today, from "
        "`registry/label-schemes/sources.yaml`; – = not published.",
        "- `n_images`: the registry's count, — = unknown. `label types`: annotation kinds, "
        "— = none declared.",
    ]  # fmt: skip
    return "\n".join(lines) + "\n"


def render_configs(published: dict[str, dict]) -> str:
    by_config: dict[str, dict[str, set]] = defaultdict(lambda: defaultdict(set))
    for sid, spec in published.items():
        by_config[spec["config"]]["sources"].add(sid)
        by_config[spec["config"]]["repo"].add(spec["repo"])
        by_config[spec["config"]]["kind"].add(spec["kind"])
    on_hub = [
        [f"`{c}`", ", ".join(sorted(v["repo"])), ", ".join(sorted(v["kind"])), _ids(v["sources"])]
        for c, v in sorted(by_config.items())
    ]
    masks = []
    for cid in tl.MASK_EXPORT_CONFIG_IDS:
        cols = mc.INSTANCE_COLUMNS if cid == "instance-masks" else mc.SEMANTIC_COLUMNS
        feeding = [s for s, c in tl.MASK_CONFIG_BY_SOURCE.items() if c == cid]
        masks.append([f"`{cid}`", _ids(feeding), _names(cols)])
    layout = [
        [f"`{hx.IMAGES}`", "Every v1 image once, keyed by `image_sha256`.", _names(hx.IMAGE_SPEC.columns)],
        [f"`{hx.MASKS}`", "Ground-truth masks, one row per (image, source).", _names(hx.MASK_COLUMNS)],
        [f"`{hx.PSEUDO_MASKS}`", "CoralSCOP model output, kept apart from ground truth.", _names(hx.MASK_COLUMNS)],
    ]  # fmt: skip
    feeds = {
        "points": tl.POINT_SOURCES, "vqa": tl.VQA_CONFIG_SOURCES, "semseg": tl.SEMSEG_SOURCES,
        "benthic-coarse": tl.ROLLUP_MASK_SOURCES, "benthic-cover": tl.ROLLUP_MASK_SOURCES,
        "bleaching": tl.BLEACHING_SOURCES, "boxes": tl.BOX_CONFIG_SOURCES,
        "depth": tl.DEPTH_CONFIG_SOURCES, "pairs": tl.PAIRS_CONFIG_SOURCES,
        "instances": tl.INSTANCE_CONFIG_SOURCES,
    }  # fmt: skip
    layers = [[f"`{c}`", _ids(feeds.get(c, ()))] for c in hx.TASK_LAYER_CONFIGS]
    excluded = [
        [f"`{c}`", _cell(hx.EXCLUDE_REASONS.get(c, ""))] for c in hx.DEFAULT_EXCLUDE_CONFIGS
    ]
    lines = [
        "# HF configs", "", HEADER, "",
        "Published configs come from `registry/label-schemes/sources.yaml`; the layout, mask and "
        "task-layer configs come from `marinedata.hf_export` and `marinedata.task_layers.configs`. "
        f"Default repo: `{hx.DEFAULT_REPO_ID}`.", "",
        "## Published on the Hub", "", *_table(["config", "repo", "kind", "sources"], on_hub), "",
        "## Mask export configs", "", *_table(["config", "sources", "columns"], masks), "",
        "## v1 export layout", "", *_table(["config", "content", "columns"], layout), "",
        "### Left out of the Hub export by default", "", *_table(["config", "reason"], excluded), "",
        "## Task-layer configs (`--tasks v2`)", "", *_table(["config", "sources"], layers),
    ]  # fmt: skip
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "docs", help="output directory")
    args = ap.parse_args(argv)
    published = published_sources(ROOT)
    registry = Registry.load(ROOT / "registry")
    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in (
        ("sources.md", render_sources(registry, published)),
        ("configs.md", render_configs(published)),
    ):
        (args.out / name).write_text(text, encoding="utf-8")
        print(f"wrote {args.out / name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
